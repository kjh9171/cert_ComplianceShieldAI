import { formatKoreanDate } from '../state';
import type { Block, DocState } from '../types';
import { officerRows, orgFull, orgShort, piiString, sensitivePii } from './helpers';

const P = (text: string): Block => ({ kind: 'paragraph', text });
const H = (num: string, text: string): Block => ({
  kind: 'heading',
  level: 2,
  num,
  text,
});
const S = (text: string): Block => ({ kind: 'heading', level: 1, text });
const L = (items: string[]): Block => ({ kind: 'list', items });

/**
 * 임직원 개인정보 보호지침
 * 「개인정보 보호법」 제28조 · 「개인정보의 안전성 확보조치 기준」 제5조
 */
export function buildSecurityGuideline(state: DocState): Block[] {
  const o = state.org;
  const p = state.processing;
  const name = orgFull(state);
  const short = orgShort(state);
  const sensitive = sensitivePii(state);

  return [
    { kind: 'title', text: `${name} 임직원 개인정보 보호지침`, subtitle: `${o.docNumber} · ${o.version}` },
    {
      kind: 'meta',
      rows: [
        ['문서관리번호', o.docNumber || '-'],
        ['문서 버전', o.version || '-'],
        ['시행일자', formatKoreanDate(o.effectiveDate)],
        ['적용 대상', '전 임직원 · 파견근로자 · 수탁자'],
        ['최종 개정일', formatKoreanDate(o.lastRevised)],
      ],
    },

    P(
      `본 지침은 ${name}(이하 “${short}”라 한다)의 모든 임직원이 업무를 수행하면서 개인정보를 취급함에 있어 준수하여야 할 사항을 정의하여, 개인정보 유출 사고를 예방하고 정보주체의 권리를 보호함을 목적으로 합니다.`,
    ),
    P(
      '본 지침은 「개인정보 보호법」 제28조 및 「개인정보의 안전성 확보조치 기준」 제5조에 근거하며, 본 지침을 위반한 경우 관련 법령 및 사내 규정에 따라 제재가 적용될 수 있습니다.',
    ),

    S('1장 기본 원칙'),

    H('1-1', '(최소수집 원칙)'),
    P(
      '임직원은 업무 수행에 필요한 최소한의 개인정보만 수집하고 수집한다. 이미 보유하고 있는 정보의 재수집, 목적 달성된 정보의 임의 사용은 금지한다.',
    ),

    H('1-2', '(목적 외 이용 금지)'),
    P(
      '수집한 개인정보는 수집 목적의 범위에서만 이용한다. 목적이 변경되는 경우에는 정보주체의 동의를 다시 받아야 하며, 임직원의 편의 또는 개인적 목적으로 이용하지 않는다.',
    ),

    H('1-3', '(안전한 처리 의무)'),
    P(
      '임직원은 개인정보를 안전하게 처리할 의무가 있으며, 개인정보가 포함된 문서의 분실, 무단 노출, 무단 복제 및 유출을 방지하기 위해 최선의 주의를 다해야 한다.'
    ),

    H('1-4', '(비밀유지 의무)'),
    P(
      '임직원은 업무를 수행하면서 알게 된 개인정보의 비밀을 지키며, 「개인정보 보호법」 제23조 및 형법 제320조에 따라 업무와 무관한 목적으로 이용하거나 타인에게 누설하여서는 아니 된다.',
    ),

    S('2장 임직원의 주요 의무사항'),

    H('2-1', '(계정 및 비밀번호 관리)'),
    L([
      '업무용 계정과 비밀번호는 본인이만 사용하고 타인에게 공유하지 않는다.',
      '비밀번호는 최소 8자리 이상으로 대문자, 소문자, 숫자, 특수문자를 조합하여 설정한다.',
      '비밀번호는 6개월에 1회 이상 변경하며, 사내망 외부에서 사용한 비밀번호는 재사용하지 않는다.',
      '다중요소 인증을 활성화하고 인증 수단을 분실하면 즉시 보안 담당자에게 신고한다.',
      '개인정보가 저장된 사내 시스템의 계정은 업무 수행에 필요한 최소 권한으로만 발급받는다.',
    ]),

    H('2-2', '(문서 및 파일 관리)'),
    L([
      '개인정보가 포함된 엑셀, 워드, PDF 파일은 반드시 암호화하여 저장하고, 암호화 비밀번호는 별도 채널로 전달한다.',
      '개인정보 문서의 파일명은 추정할 수 있는 명칭을 사용하지 않는다. 예) 고객명_최종.xlsx',
      '공용 저장장소에 개인정보 파일을 올리지 않고, 결재가 완료된 파일은 지정된 보관 위치에 저장한다.',
      '개인정보가 포함된 파일을 개인 메신저나 개인 메일로 전송하지 않는다.',
    ]),

    H('2-3', '(출력물 관리)'),
    L([
      '개인정보 출력은 필요한 최소 인원에 한하여 허가받은 자만 수행한다.',
      '출력물은 사용 즉시 회수하거나 지정된 서류보관실에 보관한다.',
      '출력물을 분리수거함에 버리지 않고, 반드시 파쇄 또는 소각 절차를 거친다.',
      '재출력한 파일에 개인정보가 남아 있지 않도록 빈 페이지를 교정하거나 삭제한다.',
    ]),

    H('2-4', '(정보화시스템 이용)'),
    L([
      '회사에서 제공하지 않은 개인 장비나 외부 서비스로 개인정보를 전송하지 않는다.',
      '개인정보처리시스템의 보안설정을 임의로 변경하거나 보안솔루션을 해제하지 않는다.',
      '모바일 기기에서 개인정보를 저장하지 않으며, 반드시 사내 보안솔루션이 설치된 단말기를 사용한다.',
      '화면 공유, 원격 지원, 화면 녹화 시 개인정보가 노출되지 않도록 개인정보 영역을 가린다.',
    ]),

    H('2-5', '(개인정보 취급 단계별 수칙)'),
    {
      kind: 'table',
      head: ['단계', '금지 행위', '준수 사항'],
      rows: [
        ['수집', '동의 없이 수집, 목적 외 항목 수집', '동의 화면과 수집 항목 대조를 월 1회 이상 확인'],
        ['검색', '무관한 사유의 대량 조회, 복사', '조회 사유를 업무일지에 기록하고 내보내기 제한을 준수'],
        ['사용', '개인적 목적의 복제·이용', '업무 목적에 한정하여 이용하고 사본을 만들지 않음'],
        ['제공', '구두·메일·메신저를 통한 제공', '승인된 절차와 시스템으로만 제공'],
        ['보관', '개인 기기·개인 계정 보관', '지정된 사내 저장소 또는 서류보관실에 보관'],
        ['파기', '휴지통 폐기, 완전 삭제 미실시', '반드시 파쇄 또는 논리적 완전삭제를 실시'],
      ],
      widths: [12, 40, 48],
    },

    S('3장 회사가 제공한 정보'),

    H('3-1', '(취급 대상 개인정보)'),
    P(`${short}에서 수집하고 처리하는 개인정보 항목은 다음과 같습니다.`),
    { kind: 'paragraph', text: `· ${piiString(state)}` },
    sensitive.length
      ? P(`민감정보로 분류되는 항목(${sensitive.join(', ')})은 별도 승인 없이 접근하거나 조회할 수 없습니다.`)
      : P('현재 법 제23조에 해당하는 민감정보는 취급하지 않습니다.'),

    H('3-2', '(접근권한 및 모니터링)'),
    P(
      '임직원의 개인정보 접근 및 변경 이력은 접속기록으로 기록되며, 회사는 이를 정기적으로 점검합니다. 비정상적인 대량 조회 또는 대량 다운로드가 감지될 경우 계정이 일시 정지되고 사용자에게 확인 절차가 진행됩니다.',
    ),

    H('3-3', '(교육 및 비밀유지 서약)'),
    P(p.trainingPolicy),

    S('4장 위반 시 조치'),

    H('4-1', '(위반 유형별 제재)'),
    {
      kind: 'table',
      head: ['구분', '위반 사례', '조치'],
      rows: [
        ['경고', '보안 게시판 누락, 서약서 미제출, 교육 미이수', '환고 조치 및 재교육'],
        ['징계', '승인 없는 개인정보 조회·복사, 관리자 우회 시도', '징계 및 권한 회수'],
        ['해임', '개인정보 유출, 무단 외부 제공, 기만적 신고 은폐', '해임 또는 퇴직 및 손해배상 청구'],
      ],
      widths: [12, 50, 38],
    },
    P(
      '① 위반 사안에 따라 회사는 「고용기준에 관한 규정」 및 관련 법령에 따른 절차의 공정성을 보장하며, 해당 임직자에게 위반 내용을 통보하고 소명할 기회를 준다.',
    ),

    H('4-2', '(유출 사고 신고의무)'),
    P(
      `① 임직원은 개인정보 유출 또는 유출이 의심되는 경우 즉시 보호책임자에게 보고해야 한다. ${p.internalReporting}`,
    ),
    P(
      '② 회사는 「개인정보 보호법」 제34조에 따라 유출 사실을 안 날부터 72시간 이내에 개인정보보호위원회에 신고하고, 정보주체에게 개별 통지한다.',
    ),

    S('5장 문의 및 신고'),

    { kind: 'table', head: ['구분', '내용'], rows: officerRows(o.cpo, '보호책임자'), widths: [30, 70] },
    P(
      '임직원은 본 지침과 관련한 문의 또는 신고를 개인정보 보호책임자에게 하면 되고, 신고자에 대해서는 불이익을 가하지 않습니다.',
    ),

    {
      kind: 'appendix',
      title: '부칙',
      blocks: [
        P(
          `① 본 지침은 ${formatKoreanDate(o.effectiveDate)}부터 시행하며, ${o.approvalBody || '대표이사'} 승인을 거쳐 제정되었습니다.`,
        ),
        P('② 본 지침은 회사가 정한 수시 기준에 따라 개정될 수 있으며, 개정된 내용은 전 임직원에게 공지한다.'),
      ],
    },

    {
      kind: 'table',
      head: ['성명 (인)', '부서', '입사일', '서약일'],
      rows: [
        [' ', ' ', ' ', ' '],
        [' ', ' ', ' ', ' '],
        [' ', ' ', ' ', ' '],
      ],
      widths: [34, 26, 20, 20],
    },
    P(
      '위 임직원은 본 지침의 내용을 숙지하였으며, 업무 수행 과정에서 알게 된 개인정보의 비밀을 준수할 것을 서약합니다.',
    ),
  ];
}